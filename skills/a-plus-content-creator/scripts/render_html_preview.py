"""
Render the A+ Content mock-up as an HTML preview.

Generates a single .html file that visually stacks all picked modules so
the buyer can see what the assembled A+ Content page will look like before
they paste anything into Amazon Seller Central.

The mock-up is NOT pixel-perfect to Amazon's actual rendering — Amazon uses
their own CSS in the editor. But it gives the buyer a structural preview of
the visual flow, image placement, and copy hierarchy.

For modules where Fal generated the image, the preview shows the actual
generated image (referenced by relative path). For Canva-brief modules, the
preview shows a placeholder block with the brief text overlaid in a soft
background.

Input JSON shape is the same as render_brief_docx.py input — this script
just renders it as HTML instead of .docx.
"""

import html
import json
import sys
from pathlib import Path


def _escape(s: str) -> str:
    return html.escape(s or "", quote=True)


def _file_header(data: dict) -> str:
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1.0" />
<title>A+ Content Preview — {_escape(data.get('product_name', 'Untitled'))}</title>
<script src="https://cdn.tailwindcss.com"></script>
<style>
  body {{ font-family: -apple-system, system-ui, sans-serif; }}
  .module-preview {{ scroll-margin-top: 80px; }}
  .canva-placeholder {{
    background: repeating-linear-gradient(45deg, #f4f4f5, #f4f4f5 10px, #e4e4e7 10px, #e4e4e7 20px);
  }}
</style>
</head>
<body class="bg-gray-50 text-gray-900">
"""


def _topbar(data: dict) -> str:
    product_name = _escape(data.get("product_name", "Untitled"))
    brand_name = _escape(data.get("brand_name", ""))
    image_source = _escape(data.get("image_source", "unknown"))
    generated_at = _escape(data.get("generated_at", ""))
    modules_count = len(data.get("modules", []) or [])
    return f"""
<div class="sticky top-0 z-10 bg-white border-b border-gray-200 shadow-sm">
  <div class="max-w-4xl mx-auto px-6 py-4">
    <div class="flex items-baseline justify-between">
      <div>
        <h1 class="text-xl font-bold text-gray-900">{product_name} — A+ Content Preview</h1>
        <p class="text-sm text-gray-600 mt-1">
          Brand: {brand_name} · Modules: {modules_count} · Image source: {image_source} · Generated {generated_at}
        </p>
      </div>
      <a href="#publishing" class="text-sm font-semibold text-gray-700 hover:text-gray-900">How to publish ↓</a>
    </div>
  </div>
</div>

<div class="max-w-4xl mx-auto px-6 py-6">
  <div class="rounded-lg bg-amber-50 border border-amber-200 p-4 mb-6">
    <p class="text-sm text-amber-900">
      <strong>Preview note:</strong> This is a structural mock-up. Amazon's actual A+ Content rendering uses their CSS,
      so spacing and typography will look slightly different in Seller Central. The copy, image dimensions, and module
      order in this preview match what you'll paste into Amazon.
    </p>
  </div>
"""


def _close(data: dict) -> str:
    return """
  <footer class="text-center text-xs text-gray-500 mt-12 py-6">
    Generated by The E-Commerce Seller plugin · A+ Content Creator
  </footer>
</div>
</body>
</html>
"""


def _publishing_block() -> str:
    return """
<div id="publishing" class="mt-12 pt-6 border-t border-gray-200">
  <h2 class="text-xl font-bold text-gray-900">How to publish this A+ Content</h2>
  <ol class="mt-4 list-decimal list-inside space-y-2 text-sm text-gray-700">
    <li>Sign into Amazon Seller Central.</li>
    <li>Brands menu → A+ Content Manager → Create A+ Content → Standard A+.</li>
    <li>For each module above, pick the matching module type from Amazon's menu, paste the copy from the .docx brief, upload the image.</li>
    <li>Use the alt text from the brief for each image (Amazon shows it in a separate field).</li>
    <li>Save & submit for Amazon review (typically 1-7 days).</li>
  </ol>
</div>
"""


def _module_preview(module: dict, index: int, base_dir: Path) -> str:
    module_id = module.get("module_id", index + 1)
    module_name = _escape(module.get("module_name", "Module"))
    purpose = _escape(module.get("purpose", ""))
    copy = module.get("copy", {}) or {}
    image = module.get("image", {}) or {}

    headline = _escape((copy.get("headline") or {}).get("text", ""))
    body_text = _escape((copy.get("body") or {}).get("text", ""))

    # Image rendering
    img_block = ""
    src = image.get("source", "unknown")
    if src == "fal" and image.get("generated_path"):
        gen_path = Path(image["generated_path"])
        try:
            rel = gen_path.relative_to(base_dir)
            rel_str = str(rel).replace("\\", "/")
        except ValueError:
            rel_str = str(gen_path).replace("\\", "/")
        img_block = (
            f'<img src="{_escape(rel_str)}" alt="{_escape((copy.get("image_alt") or {}).get("text", ""))}" '
            f'class="w-full h-auto rounded-lg shadow-sm" />'
        )
    elif src == "canva_brief":
        brief = _escape(image.get("canva_brief", "")[:400] + ("..." if len(image.get("canva_brief", "")) > 400 else ""))
        spec = _escape(image.get("spec_dimensions", ""))
        img_block = f"""
<div class="canva-placeholder rounded-lg p-6 min-h-[200px]">
  <div class="bg-white/90 rounded p-4 text-sm text-gray-700">
    <p class="font-semibold text-gray-900 mb-2">Canva brief — image to be created</p>
    <p class="text-xs text-gray-500 mb-3">Required dimensions: {spec}</p>
    <p class="whitespace-pre-wrap">{brief}</p>
  </div>
</div>"""
    elif src == "use_your_own_photo":
        notes = _escape(image.get("notes", ""))
        spec = _escape(image.get("spec_dimensions", ""))
        img_block = f"""
<div class="canva-placeholder rounded-lg p-6 min-h-[120px] flex items-center">
  <div class="bg-white/90 rounded p-4 text-sm text-gray-700 w-full">
    <p class="font-semibold text-gray-900">Use your own photo</p>
    <p class="text-xs text-gray-500 mt-1">Required dimensions: {spec}</p>
    <p class="mt-2">{notes}</p>
  </div>
</div>"""

    purpose_block = (
        f'<p class="text-xs text-gray-500 italic mb-3">{purpose}</p>' if purpose else ""
    )

    return f"""
<section id="module-{index + 1}" class="module-preview bg-white rounded-lg shadow-sm border border-gray-200 p-6 mb-6">
  <div class="text-xs text-gray-500 uppercase tracking-wide mb-2">
    Module {index + 1} · Amazon Module ID {module_id} · {module_name}
  </div>
  {purpose_block}
  <div class="grid grid-cols-1 md:grid-cols-2 gap-6 mt-4">
    <div>{img_block}</div>
    <div>
      <h3 class="text-xl font-bold text-gray-900">{headline}</h3>
      <p class="mt-3 text-base text-gray-700 leading-relaxed">{body_text}</p>
    </div>
  </div>
</section>
"""


def render(data: dict, output_path: Path) -> Path:
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    base_dir = output_path.parent

    parts: list[str] = []
    parts.append(_file_header(data))
    parts.append(_topbar(data))

    modules = data.get("modules", []) or []
    for i, module in enumerate(modules):
        parts.append(_module_preview(module, i, base_dir))

    parts.append(_publishing_block())
    parts.append(_close(data))

    output_path.write_text("".join(parts), encoding="utf-8")
    return output_path


if __name__ == "__main__":
    if len(sys.argv) < 3:
        print("Usage: python render_html_preview.py <brief_json> <output_path>")
        sys.exit(1)
    with open(sys.argv[1], "r", encoding="utf-8") as f:
        data = json.load(f)
    out = render(data, Path(sys.argv[2]))
    print(f"Wrote {out}")
